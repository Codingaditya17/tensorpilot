#!/usr/bin/env bash
# PID 1 of the experiment Pod. Runs as root only long enough to prepare /workspace and start sshd;
# every TensorPilot process runs as the unprivileged `tensorpilot` user after an SSH login.
#
# Fails closed: without a valid PUBLIC_KEY (Runpod injects your account's public key) sshd is not
# started and the container exits, so a Pod is never left reachable without key authentication.
set -euo pipefail

USER_NAME=tensorpilot
HOME_DIR="/home/$USER_NAME"
MAX_MINUTES="${TENSORPILOT_POD_MAX_MINUTES:-120}"

if [[ -z "${PUBLIC_KEY:-}" ]]; then
  echo "PUBLIC_KEY is not set; refusing to start without SSH key authentication" >&2
  exit 1
fi
KEY_RE='^(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp[0-9]+|sk-ssh-ed25519@openssh\.com) [A-Za-z0-9+/=]+( .*)?$'
keys="$(printf '%s\n' "$PUBLIC_KEY" | sed '/^[[:space:]]*$/d')"
if [[ -z "$keys" ]] || printf '%s\n' "$keys" | grep -qvE "$KEY_RE"; then
  echo "PUBLIC_KEY must contain only plain public keys (no options, no private key material)" >&2
  exit 1
fi
if ! [[ "$MAX_MINUTES" =~ ^[0-9]+$ ]] || (( MAX_MINUTES < 1 )); then
  echo "TENSORPILOT_POD_MAX_MINUTES must be a positive integer" >&2
  exit 1
fi

# Storage. A mounted volume may arrive root-owned and may refuse chown even for root (Runpod's does).
# The truth is whether the unprivileged user can really write there, so each directory is probed as
# that user. Order: use it as is, else try to chown it, else fall back to container disk, else stop
# with a diagnostic. Nothing is assumed writable because a command exited 0.
FALLBACK_ROOT="/home/$USER_NAME/work"

probe_writable() {  # create, read back and delete a file in $1 as the unprivileged user
  runuser -u "$USER_NAME" -- bash -c \
    'f="$(mktemp "$1/.tp-probe.XXXXXX")" && printf ok >"$f" && [ "$(cat "$f")" = ok ] && rm -f "$f"' _ "$1" 2>/dev/null
}

prepare_dir() {  # returns 0 only if $1 is verified writable by the unprivileged user
  local dir="$1" err
  runuser -u "$USER_NAME" -- mkdir -p "$dir" 2>/dev/null || true
  probe_writable "$dir" && return 0
  mkdir -p "$dir" 2>/dev/null || true
  if ! err="$(chown "$USER_NAME:$USER_NAME" "$dir" 2>&1)"; then
    echo "storage: chown of $dir refused: ${err:-no message}" >&2
  fi
  probe_writable "$dir"
}

storage_diagnostic() {
  {
    echo "storage diagnostic for $1:"
    ls -ldn "$1" 2>&1 || true
    echo "  entrypoint identity: $(id)"
    grep " $(dirname "$1") " /proc/mounts 2>/dev/null | sed 's/^/  mount: /' || true
    df -h "$(dirname "$1")" 2>&1 | sed 's/^/  /' || true
  } >&2
}

select_dir() {  # name -> prints the chosen directory; stdout carries only the path
  local name="$1" preferred="/workspace/$1" fallback="$FALLBACK_ROOT/$1"
  if prepare_dir "$preferred"; then
    echo "storage: $name -> $preferred (mounted volume, verified writable)" >&2
    printf '%s\n' "$preferred"; return 0
  fi
  storage_diagnostic "$preferred"
  if prepare_dir "$fallback"; then
    echo "storage: WARNING $name -> $fallback (container disk fallback; it does not survive a Pod stop, export evidence before stopping)" >&2
    printf '%s\n' "$fallback"; return 0
  fi
  storage_diagnostic "$fallback"
  echo "storage: no writable storage for $name: neither $preferred nor $fallback accepts writes from $USER_NAME" >&2
  return 1
}

RESULTS_ROOT="$(select_dir results)" || exit 1
CACHE_DIR="$(select_dir huggingface)" || exit 1
if ! runuser -u "$USER_NAME" -- chmod 0700 "$RESULTS_ROOT" 2>/dev/null; then
  echo "storage: could not restrict $RESULTS_ROOT to mode 0700; it keeps its existing mode" >&2
fi

# Created by the user itself, so no chown is needed and the ownership sshd's StrictModes checks is correct.
printf '%s\n' "$keys" | runuser -u "$USER_NAME" -- bash -c \
  'umask 077 && mkdir -p "$1/.ssh" && cat >"$1/.ssh/authorized_keys"' _ "$HOME_DIR"
runuser -u "$USER_NAME" -- test -s "$HOME_DIR/.ssh/authorized_keys" \
  || { echo "could not write $HOME_DIR/.ssh/authorized_keys as $USER_NAME" >&2; exit 1; }

# SSH sessions do not inherit the container environment. Forward an allowlist of non-secret
# settings through a profile script. API keys are deliberately not forwarded: generate them in the
# session with pod-keys.sh so they never sit in Runpod's configuration or on disk.
{
  echo "# generated by pod-entrypoint.sh"
  for name in TENSORPILOT_MODEL TENSORPILOT_REVISION TENSORPILOT_BENCH_CONFIG \
              TENSORPILOT_BENCH_TIMEOUT TENSORPILOT_SESSION_CAP TENSORPILOT_POD_MAX_MINUTES; do
    [[ -n "${!name:-}" ]] && printf 'export %s=%q\n' "$name" "${!name}"
  done
  # The directories the verified probe selected: first-run.sh, session.sh and the cache all follow them.
  printf 'export TENSORPILOT_RESULTS_ROOT=%q\n' "$RESULTS_ROOT"
  printf 'export TENSORPILOT_CACHE_DIR=%q\n' "$CACHE_DIR"
  printf 'export HF_HOME=%q\n' "$CACHE_DIR"
  echo 'export PATH="/opt/tensorpilot/deploy/runpod:$PATH"'
  printf 'case $- in *i*) echo "TensorPilot Pod: evidence -> %s | model cache -> %s" ;; esac\n' "$RESULTS_ROOT" "$CACHE_DIR"
  echo 'cd /opt/tensorpilot 2>/dev/null || true'
} >/etc/profile.d/tensorpilot.sh
chmod 0644 /etc/profile.d/tensorpilot.sh

[[ -f /etc/ssh/ssh_host_ed25519_key ]] || ssh-keygen -q -t ed25519 -N '' -f /etc/ssh/ssh_host_ed25519_key
/usr/sbin/sshd -t

/usr/sbin/sshd -D -e &
SSHD_PID=$!
stop() { kill -TERM "$SSHD_PID" 2>/dev/null || true; wait "$SSHD_PID" 2>/dev/null || true; exit 0; }
trap stop TERM INT

echo "sshd ready on :22 as user $USER_NAME; evidence $RESULTS_ROOT; cache $CACHE_DIR; max Pod lifetime ${MAX_MINUTES} minutes" >&2
deadline=$((SECONDS + MAX_MINUTES * 60))
while kill -0 "$SSHD_PID" 2>/dev/null; do
  if (( SECONDS >= deadline )); then
    echo "maximum Pod lifetime reached; exiting so GPU billing stops. Terminate the Pod in the console." >&2
    stop
  fi
  sleep 5 &
  wait $! || true
done
echo "sshd exited unexpectedly" >&2
exit 1
