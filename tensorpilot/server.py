"""TensorPilot inference service. One process owns one model on one accelerator.

The MLX backend runs on Apple silicon. The CUDA backend runs on NVIDIA Linux hosts.
Both satisfy the same InferenceBackend contract, so the HTTP API, admission and
lifecycle behavior are identical across runtimes.
"""
import argparse
import asyncio
import hmac
import json
import logging
import math
import os
import platform
import time
import uuid
from importlib.metadata import version

from aiohttp import web
from prometheus_client import CONTENT_TYPE_LATEST

from . import __version__
from . import quantization
from .backend import BACKENDS, MLXBackend
from .bench import DEFAULT_MODEL
from .engine import Engine, Overloaded
from .batch_engine import BatchEngine
from .cuda_backend import CUDABackend
from .environment import source_fingerprint, dependency_versions
from .metrics import Metrics
from .scheduler import Scheduler
from .ui import DASHBOARD_HTML
from .admission import ResourceAdmission
from .adaptive import AdaptiveBatchController
from .gpu_telemetry import GPUTelemetry

ENGINE = web.AppKey("engine", Engine)
METRICS = web.AppKey("metrics", Metrics)
LOGGER = logging.getLogger("tensorpilot.http")
# RequestKey was introduced after aiohttp 3.12; preserve compatibility.
REQUEST_ID = web.RequestKey("request_id", str) if hasattr(web, "RequestKey") else "request_id"


def create_app(factory, *, queue_size=8, max_tokens=256, max_timeout=120,
               warmup=True, metadata=None, api_key=None, scheduler="fifo", max_queue_wait_s=1.0,
               instance_id=None, stall_timeout_s=30.0, execution="serial", batch_size=2,
               prefill_step_size=256, batch_adapter_factory=None,
               admission_memory_bytes=512 * 1024**2, admission_bytes_per_token=16 * 1024,
               adaptive_latency_target_s=.25, adaptive_memory_soft_limit=.85,
               adaptive_memory_hard_limit=.95, gpu_telemetry=None):
    metrics = Metrics()
    admission = ResourceAdmission(admission_memory_bytes, bytes_per_token=admission_bytes_per_token)
    options = {"metrics": metrics, "scheduler": scheduler, "admission": admission,
               "max_queue_wait_s": max_queue_wait_s, "stall_timeout_s": stall_timeout_s}
    if execution in ("batch", "adaptive"):
        options.update(max_batch_size=batch_size, prefill_step_size=prefill_step_size)
        if execution == "adaptive":
            options["adaptive_controller"] = AdaptiveBatchController(
                batch_size, latency_target_s=adaptive_latency_target_s,
                memory_soft_limit=adaptive_memory_soft_limit,
                memory_hard_limit=adaptive_memory_hard_limit)
        if batch_adapter_factory is not None:
            options["adapter_factory"] = batch_adapter_factory
        engine = BatchEngine(factory, queue_size, **options)
    elif execution == "serial":
        engine = Engine(factory, queue_size, **options)
    else:
        raise ValueError("execution must be serial, batch or adaptive")
    service_metadata = {**(metadata or {}), "instance_id": instance_id or uuid.uuid4().hex,
                        "scheduler": scheduler, "max_queue_wait_s": max_queue_wait_s,
                        "service_version": __version__}
    service_metadata["stall_timeout_s"] = stall_timeout_s
    service_metadata.update(execution_mode=execution, max_active_sequences=engine.max_active_sequences,
                            prefill_step_size=prefill_step_size if execution != "serial" else 2048)

    def error(request, status, code, message, headers=None):
        return web.json_response({"error": {"code": code, "message": message},
                                  "request_id": request[REQUEST_ID]},
                                 status=status, headers=headers)

    @web.middleware
    async def operations(request, handler):
        # Generated by the service; untrusted caller IDs never enter logs/labels.
        request[REQUEST_ID] = uuid.uuid4().hex
        started = time.perf_counter()
        status = 500
        try:
            # The dashboard shell is public so an operator can enter a key in it;
            # data/model/generation endpoints remain protected.
            protected = request.path not in ("/", "/livez", "/readyz")
            supplied = request.headers.get("Authorization", "")
            if api_key and protected and not hmac.compare_digest(supplied.encode(), ("Bearer " + api_key).encode()):
                response = error(request, 401, "unauthorized", "A valid bearer token is required",
                                 {"WWW-Authenticate": "Bearer"})
            else:
                try:
                    response = await handler(request)
                except web.HTTPException as exc:
                    codes = {400: "invalid_request", 404: "not_found", 405: "method_not_allowed",
                             413: "request_too_large", 503: "overloaded"}
                    response = error(request, exc.status, codes.get(exc.status, "http_error"),
                                     exc.reason, {k: v for k, v in exc.headers.items()
                                                  if k.lower() in ("allow", "retry-after")})
                except Exception as exc:
                    LOGGER.error(json.dumps({"event": "handler_error", "request_id": request[REQUEST_ID],
                                             "error_type": type(exc).__name__}))
                    response = error(request, 500, "internal_error", "Internal service error")
            status = response.status
            if not response.prepared:
                response.headers["X-Request-ID"] = request[REQUEST_ID]
            return response
        except asyncio.CancelledError:
            status = 499
            raise
        finally:
            metrics.http.labels(status=str(status)).inc()
            LOGGER.info(json.dumps({"event": "http_request", "request_id": request[REQUEST_ID],
                                    "method": request.method, "status": status,
                                    "elapsed_s": time.perf_counter() - started}))

    app = web.Application(client_max_size=32 * 1024, middlewares=[operations])
    app[ENGINE], app[METRICS] = engine, metrics

    async def lifecycle(app):
        if gpu_telemetry is not None:
            await gpu_telemetry.start()
        try:
            await engine.start(warmup)
            provenance = await engine.call(lambda: getattr(engine.backend, "provenance", {}))
            service_metadata.update(provenance)
            yield
        finally:
            await engine.close()
            if gpu_telemetry is not None:
                await gpu_telemetry.close()

    async def shutdown(app):
        await engine.close()

    def ready():
        return engine.ready

    async def livez(request):
        return web.json_response({"alive": True})

    async def dashboard(request):
        return web.Response(text=DASHBOARD_HTML, content_type="text/html",
                            headers={"Cache-Control": "no-store",
                                     "Content-Security-Policy": "default-src 'self'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; connect-src 'self'; object-src 'none'; base-uri 'none'"})

    async def readyz(request):
        available = ready()
        return web.json_response({"ready": available, "reason": engine.unhealthy_reason}, status=200 if available else 503)

    async def health(request):
        return web.json_response({"ready": ready(), "queue_depth": engine.queue.qsize(),
                                  "unhealthy_reason": engine.unhealthy_reason,
                                  "active": engine.active is not None,
                                  "active_sequences": engine.active_count,
                                  "execution_concurrency": engine.max_active_sequences,
                                  "admission": engine.admission.snapshot(),
                                  "last_measured_memory": engine.last_memory_sample,
                                  "startup_profile": engine.startup_profile,
                                  "gpu_telemetry": gpu_telemetry.snapshot() if gpu_telemetry else None,
                                  "runtime_profile": engine.runtime_profile(),
                                  "kv_pool": (engine.adapter.snapshot()
                                              if hasattr(getattr(engine, "adapter", None), "snapshot") else None),
                                  "adaptive_policy": (engine.adaptive_controller.snapshot()
                                                      if getattr(engine, "adaptive_controller", None) else None),
                                  "memory_sample_age_s": (time.perf_counter() - engine.last_memory_sample_s
                                                          if engine.last_memory_sample_s is not None else None),
                                  **service_metadata})

    async def model_info(request):
        return web.json_response({"api_version": "v1", "execution_concurrency": engine.max_active_sequences,
                                  "max_output_tokens": max_tokens,
                                  "max_timeout_s": max_timeout, **service_metadata})

    async def prometheus(request):
        return web.Response(body=metrics.render(engine), headers={"Content-Type": CONTENT_TYPE_LATEST})

    async def generate(request):
        try:
            body = await request.json()
            if not isinstance(body, dict):
                raise ValueError("body must be a JSON object")
            if set(body) - {"prompt", "max_tokens", "timeout_s"}:
                raise ValueError("unsupported request field")
            prompt = body["prompt"]
            count = body.get("max_tokens", min(64, max_tokens))
            timeout = body.get("timeout_s", min(60, max_timeout))
            if not isinstance(prompt, str) or not prompt.strip() or len(prompt.encode()) > 16384:
                raise ValueError("prompt must contain 1–16384 UTF-8 bytes")
            if type(count) is not int or not 1 <= count <= max_tokens:
                raise ValueError(f"max_tokens must be an integer in 1..{max_tokens}")
            if type(timeout) not in (int, float) or not math.isfinite(timeout) or not 0 < timeout <= max_timeout:
                raise ValueError(f"timeout_s must be in (0, {max_timeout}]")
        except (ValueError, KeyError, TypeError) as exc:
            return error(request, 400, "invalid_request", str(exc))
        if not ready():
            return error(request, 503, "unavailable", "Inference worker is unavailable", {"Retry-After": "1"})
        try:
            job = engine.submit(prompt, count, timeout, request_id=request[REQUEST_ID])
        except Overloaded as exc:
            return error(request, 503, "overloaded", str(exc), {"Retry-After": "1"})
        response = web.StreamResponse(headers={"Content-Type": "application/x-ndjson",
                                               "X-Request-ID": job.request_id,
                                               "Cache-Control": "no-store"})
        # The handler knows why it stops, so the engine records the right outcome without comparing clocks.
        reason = "cancelled"
        try:
            await response.prepare(request)
            async with asyncio.timeout(timeout):
                while True:
                    event = await job.events.get()
                    await response.write((json.dumps({**event, "request_id": job.request_id}) + "\n").encode())
                    if event["type"] in ("done", "error"):
                        break
            await response.write_eof()
        except TimeoutError:
            # A slow client must not hold the handler beyond the deadline. The
            # consumer treats a stream without a terminal event as failed.
            reason = "deadline_exceeded"
            response.force_close()
        except ConnectionError:
            response.force_close()
        finally:
            engine.cancel(job, reason)
        return response

    app.cleanup_ctx.append(lifecycle)
    app.on_shutdown.append(shutdown)
    app.router.add_get("/", dashboard)
    app.router.add_get("/livez", livez)
    app.router.add_get("/readyz", readyz)
    app.router.add_get("/health", health)
    app.router.add_get("/metrics", prometheus)
    app.router.add_get("/v1/model", model_info)
    app.router.add_post("/v1/generate", generate)
    app.router.add_post("/generate", generate)  # v0.2 compatibility
    return app


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--backend", choices=BACKENDS, default=os.environ.get("TENSORPILOT_BACKEND", "mlx"),
                        help="mlx: Apple silicon; cuda: Linux NVIDIA through PyTorch and Transformers")
    parser.add_argument("--model", default=os.environ.get("TENSORPILOT_MODEL", DEFAULT_MODEL),
                        help="MLX model or Hugging Face repository; cuda needs a Transformers checkpoint")
    parser.add_argument("--revision", default=os.environ.get("TENSORPILOT_REVISION"),
                        help="Hugging Face commit/tag; resolved commit and artifact hash are recorded")
    parser.add_argument("--offline", action="store_true", help="load only an already-cached model snapshot")
    parser.add_argument("--cache-dir", default=os.environ.get("TENSORPILOT_CACHE_DIR"),
                        help="Hugging Face hub cache directory for downloaded snapshots")
    parser.add_argument("--profile-memory", action="store_true", help="opt-in per-token KV/MLX memory snapshots; adds overhead")
    parser.add_argument("--instance-id", help=argparse.SUPPRESS)
    parser.add_argument("--host", default=os.environ.get("TENSORPILOT_HOST", "127.0.0.1"))
    parser.add_argument("--port", type=int, default=int(os.environ.get("TENSORPILOT_PORT", "8080")))
    parser.add_argument("--queue-size", type=int, default=8)
    parser.add_argument("--max-output-tokens", type=int, default=512,
                        help="service output cap (1..512)")
    parser.add_argument("--max-prompt-tokens", type=int, default=2048,
                        help="prompt token cap, enforced before inference (1..8192)")
    parser.add_argument("--execution", choices=("serial", "batch", "adaptive"), default="serial",
                        help="batch is opt-in real continuous batching (MLX, or CUDA for Qwen2/Llama models)")
    parser.add_argument("--batch-size", type=int, default=2,
                        help="maximum active batch sequences (1..8 for MLX; 1..256 for CUDA, reduced to fit the KV pool)")
    parser.add_argument("--kv-budget-gib", type=float, default=0,
                        help="CUDA batch: KV slot pool budget in GiB; 0 sizes it from free VRAM")
    parser.add_argument("--kv-headroom-gib", type=float, default=2.5,
                        help="CUDA batch: VRAM kept free of weights and KV for activations and allocator overhead")
    parser.add_argument("--prefill-step-size", type=int, default=256, help="batch prefill segmentation (1..2048)")
    parser.add_argument("--adaptive-latency-target", type=float, default=.25,
                        help="oldest queue wait that triggers maximum adaptive width")
    parser.add_argument("--adaptive-memory-soft-limit", type=float, default=.85,
                        help="estimated reservation pressure that caps adaptive width at two")
    parser.add_argument("--adaptive-memory-hard-limit", type=float, default=.95,
                        help="estimated reservation pressure that caps adaptive width at one")
    parser.add_argument("--memory-gib", type=float, default=6, help="MLX memory limit")
    parser.add_argument("--device", default=os.environ.get("TENSORPILOT_DEVICE", "cuda"),
                        help="CUDA device, for example cuda or cuda:0")
    parser.add_argument("--dtype", choices=("float16", "bfloat16", "float32"), default="float16",
                        help="CUDA model weight dtype")
    parser.add_argument("--quantization", choices=quantization.MODES,
                        default=os.environ.get("TENSORPILOT_QUANTIZATION", "none"),
                        help="CUDA weight quantization: none keeps --dtype weights; nf4 is bitsandbytes 4-bit NormalFloat "
                             "with double quantization. Chosen explicitly; never an automatic fallback")
    parser.add_argument("--cuda-memory-fraction", type=float, default=.9,
                        help="per-process CUDA allocator cap in (0, 1]")
    parser.add_argument("--gpu-telemetry-interval", type=float, default=2.0,
                        help="nvidia-smi sample period in seconds; 0 disables; CUDA only")
    parser.add_argument("--admission-memory-mib", type=int, default=512,
                        help="estimated KV reservation budget; separate from measured MLX memory")
    parser.add_argument("--admission-bytes-per-token", type=int, default=16 * 1024,
                        help="conservative KV estimate coefficient, not a measurement")
    parser.add_argument("--scheduler", choices=Scheduler.POLICIES, default="fifo")
    parser.add_argument("--max-queue-wait", type=float, default=1.0,
                        help="aging override threshold in seconds; never preempts active inference")
    parser.add_argument("--stall-timeout", type=float, default=30,
                        help="mark backend unhealthy if one model-thread call exceeds this duration")
    args = parser.parse_args()
    if (args.queue_size < 1 or not 0 < args.memory_gib <= 8 or
            not 1 <= args.max_output_tokens <= 512):
        parser.error("queue-size must be positive; memory-gib in (0, 8]; output cap in 1..512")
    if not 1 <= args.max_prompt_tokens <= 8192:
        parser.error("max-prompt-tokens must be in 1..8192")
    if args.admission_memory_mib < 1 or args.admission_bytes_per_token < 1:
        parser.error("admission memory and bytes-per-token must be positive")
    if not math.isfinite(args.max_queue_wait) or args.max_queue_wait <= 0:
        parser.error("max-queue-wait must be finite and positive")
    if not math.isfinite(args.stall_timeout) or args.stall_timeout <= 0:
        parser.error("stall-timeout must be finite and positive")
    width_limit = 256 if args.backend == "cuda" else 8
    if not 1 <= args.batch_size <= width_limit or not 1 <= args.prefill_step_size <= 2048:
        parser.error(f"batch-size must be in 1..{width_limit} for the {args.backend} backend; "
                     "prefill-step-size in 1..2048")
    if args.kv_budget_gib < 0 or args.kv_headroom_gib < 0:
        parser.error("kv-budget-gib and kv-headroom-gib cannot be negative")
    if (not math.isfinite(args.adaptive_latency_target) or args.adaptive_latency_target <= 0 or
            not 0 < args.adaptive_memory_soft_limit < args.adaptive_memory_hard_limit <= 1):
        parser.error("adaptive target must be positive and 0 < soft memory limit < hard limit <= 1")
    if args.execution == "batch" and args.profile_memory:
        parser.error("--profile-memory is currently supported only by serial execution")
    if args.backend == "cuda":
        if args.model == DEFAULT_MODEL:
            parser.error("--backend cuda needs --model naming a Transformers checkpoint; the MLX default is not loadable")
        if args.execution == "adaptive":
            parser.error("--execution adaptive is MLX-only; the CUDA backend supports serial and batch")
        if args.profile_memory:
            parser.error("--profile-memory is MLX-only")
        if not 0 < args.cuda_memory_fraction <= 1:
            parser.error("cuda-memory-fraction must be in (0, 1]")
        if args.quantization != "none":
            if args.dtype == "float32":
                parser.error("--quantization nf4 computes in float16 or bfloat16; choose --dtype accordingly")
            try:
                quantization.require_stack(args.quantization)
            except quantization.QuantizationUnavailable as error:
                parser.error(str(error))
    elif args.quantization != "none":
        parser.error("--quantization is CUDA-only; the MLX backend loads its own pre-quantized models")
        if not math.isfinite(args.gpu_telemetry_interval) or args.gpu_telemetry_interval < 0:
            parser.error("gpu-telemetry-interval must be finite and nonnegative")
    api_key = os.environ.get("TENSORPILOT_API_KEY")
    if args.host not in ("127.0.0.1", "localhost", "::1") and not api_key:
        parser.error("set TENSORPILOT_API_KEY before binding a non-loopback address")
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    common = {"server_platform": platform.platform(), "server_python": platform.python_version(),
              "source_sha256": source_fingerprint(), "dependencies": dependency_versions(),
              "max_prompt_tokens": args.max_prompt_tokens, "max_output_tokens": args.max_output_tokens,
              "queue_capacity": args.queue_size, "sampling": "greedy",
              "prompt_format": "raw text, tokenizer default special tokens"}
    telemetry = None
    if args.backend == "mlx":
        metadata = {"model": args.model, "backend": "mlx", "warmup": True,
                    "mlx_lm_version": version("mlx-lm"), "mlx_version": version("mlx"),
                    "memory_limit_bytes": int(args.memory_gib * 1024**3), **common}

        def factory():
            return MLXBackend(args.model, metadata["memory_limit_bytes"], args.max_prompt_tokens,
                              revision=args.revision, offline=args.offline,
                              profile_memory=args.profile_memory, cache_dir=args.cache_dir)
    else:
        metadata = {"model": args.model, "backend": "cuda", "warmup": True, "quantization_mode": args.quantization,
                    **common}
        if args.gpu_telemetry_interval > 0:
            telemetry = GPUTelemetry(args.gpu_telemetry_interval)

        def factory():
            return CUDABackend(args.model, max_prompt_tokens=args.max_prompt_tokens,
                               revision=args.revision, offline=args.offline, device=args.device,
                               dtype=args.dtype, memory_fraction=args.cuda_memory_fraction,
                               cache_dir=args.cache_dir, quantization=args.quantization)
    adapter_factory = None
    if args.backend == "cuda" and args.execution == "batch":
        from .cuda_batch import CUDABatchAdapterFactory
        adapter_factory = CUDABatchAdapterFactory(
            kv_budget_bytes=int(args.kv_budget_gib * 1024**3) or None,
            headroom_bytes=int(args.kv_headroom_gib * 1024**3))
    app = create_app(factory,
                     queue_size=args.queue_size, max_tokens=args.max_output_tokens,
                     metadata=metadata, api_key=api_key,
                     scheduler=args.scheduler, max_queue_wait_s=args.max_queue_wait,
                     instance_id=args.instance_id, stall_timeout_s=args.stall_timeout,
                     execution=args.execution, batch_size=args.batch_size,
                     prefill_step_size=args.prefill_step_size,
                     admission_memory_bytes=args.admission_memory_mib * 1024**2,
                     admission_bytes_per_token=args.admission_bytes_per_token,
                     adaptive_latency_target_s=args.adaptive_latency_target,
                     adaptive_memory_soft_limit=args.adaptive_memory_soft_limit,
                     adaptive_memory_hard_limit=args.adaptive_memory_hard_limit,
                     gpu_telemetry=telemetry, batch_adapter_factory=adapter_factory)
    web.run_app(app, host=args.host, port=args.port, handler_cancellation=True, access_log=None)


if __name__ == "__main__":
    main()
